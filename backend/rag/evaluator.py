import re
from typing import List, Dict, Any, Tuple
from backend.rag.retriever import rag_retriever
from backend.agents.rag_agent import rag_agent


class RAGEvaluator:
    """
    Automated evaluation harness for Vector RAG pipeline faithfulness,
    citation precision, hallucination detection, and negative control abstention.
    Inspired by the Ragas / LLM-as-a-judge evaluation methodology.
    """

    def __init__(self):
        self.retriever = rag_retriever
        self.agent = rag_agent

    @staticmethod
    def extract_numerical_entities(text: str) -> List[str]:
        """
        Extracts numbers, percentages, basis points, and currency amounts
        to verify numerical faithfulness against source context.
        """
        # Matches patterns like 18%, 140 bps, $9.80, 10.2 billion, 104%, 122%
        pattern = r"(\$?\d+(?:\.\d+)?(?:\s*(?:%|bps|basis points|billion|million|bbl))?)"
        matches = re.findall(pattern, text, re.IGNORECASE)
        # Filter out bare single digits like '1' or '2' unless followed by units
        return [m.strip() for m in matches if len(m.strip()) > 1 or m.strip().isdigit() and int(m.strip()) > 9]

    def evaluate_faithfulness(self, findings: List[str], citations: List[Dict[str, Any]]) -> Tuple[float, List[Dict[str, Any]]]:
        """
        Evaluates whether findings generated by the RAG agent are strictly
        grounded in the retrieved citation excerpts. Checks entity and numerical preservation.
        Returns a score between 0.0 and 1.0.
        """
        if not findings:
            return 1.0, []

        if not citations:
            return 0.0, [{"finding": f, "status": "UNGROUNDED_NO_CONTEXT"} for f in findings]

        # Combine all citation fields into reference context
        context_parts = []
        for c in citations:
            context_parts.append(c.get("document_title", ""))
            context_parts.append(c.get("section", ""))
            context_parts.append(c.get("fiscal_period", ""))
            context_parts.append(c.get("excerpt", ""))
            context_parts.append(c.get("full_context", ""))
        combined_context = " ".join(context_parts).lower()

        detailed_checks = []
        grounded_count = 0

        for finding in findings:
            finding_lower = finding.lower()
            # Extract claim payload inside quotation marks if formatted as Doc Title (Section): "..."
            if '"' in finding:
                claim_part = finding.split('"')[1]
            else:
                claim_part = finding

            numbers = self.extract_numerical_entities(claim_part)

            # Check if all numbers in the claim exist in the source filing
            unsupported_numbers = []
            for num in numbers:
                # Clean up unit for relaxed matching
                clean_num = num.replace("$", "").replace("%", "").strip().lower()
                # Split compound like '140 basis points' -> '140'
                num_digits = re.search(r"\d+(?:\.\d+)?", clean_num)
                val_to_check = num_digits.group(0) if num_digits else clean_num
                if val_to_check not in combined_context:
                    unsupported_numbers.append(num)

            # Substring / keyword overlap check
            claim_words = [w for w in re.findall(r"\w+", claim_part.lower()) if len(w) > 3]
            overlap_words = [w for w in claim_words if w in combined_context]
            overlap_ratio = len(overlap_words) / len(claim_words) if claim_words else 1.0

            is_grounded = len(unsupported_numbers) == 0 and overlap_ratio >= 0.50
            if is_grounded:
                grounded_count += 1

            detailed_checks.append({
                "finding": finding,
                "is_grounded": is_grounded,
                "overlap_ratio": round(overlap_ratio, 2),
                "unsupported_numbers": unsupported_numbers
            })

        faithfulness_score = round(grounded_count / len(findings), 2)
        return faithfulness_score, detailed_checks

    def evaluate_abstention(self, uncataloged_ticker: str) -> Dict[str, Any]:
        """
        Verifies that the RAG pipeline cleanly abstains on unknown or uncataloged tickers:
        - 0 citations returned
        - Default neutral stance & score = 50
        - Clear refusal notice instead of hallucinated metrics
        """
        res = self.agent.analyze(uncataloged_ticker)
        has_zero_citations = len(res.get("citations", [])) == 0
        is_neutral = res.get("score") == 50 and res.get("stance") == "NEUTRAL"
        abstention_message_present = any("pending corporate filing upload" in f.lower() or "no regulatory filings" in f.lower() for f in res.get("key_findings", []))

        passed = has_zero_citations and is_neutral and abstention_message_present
        return {
            "ticker": uncataloged_ticker,
            "passed": passed,
            "has_zero_citations": has_zero_citations,
            "is_neutral_score": is_neutral,
            "refusal_reason_logged": abstention_message_present,
            "citations_count": len(res.get("citations", []))
        }

    def run_benchmark_suite(self) -> Dict[str, Any]:
        """
        Executes an end-to-end evaluation suite over cataloged, dynamic,
        and uncataloged assets.
        """
        test_tickers = ["RELIANCE", "NVDA", "TCS", "INFY"]
        negative_controls = ["CUSTOMTECH", "UNKNOWN_CORP_99"]

        results = []
        faithfulness_scores = []
        citation_counts = []

        # 1. Evaluate cataloged assets
        for ticker in test_tickers:
            res = self.agent.analyze(ticker)
            citations = res.get("citations", [])
            findings = res.get("key_findings", [])

            score, checks = self.evaluate_faithfulness(findings, citations)
            faithfulness_scores.append(score)
            citation_counts.append(len(citations))

            results.append({
                "ticker": ticker,
                "type": "CATALOGED",
                "citations_retrieved": len(citations),
                "faithfulness_score": score,
                "checks": checks
            })

        # 2. Evaluate negative control abstention
        abstention_results = []
        for neg in negative_controls:
            abs_res = self.evaluate_abstention(neg)
            abstention_results.append(abs_res)

        avg_faithfulness = round(sum(faithfulness_scores) / len(faithfulness_scores), 2) if faithfulness_scores else 1.0
        hallucination_rate = round(1.0 - avg_faithfulness, 2)
        all_abstentions_passed = all(a["passed"] for a in abstention_results)

        return {
            "benchmark_status": "PASSED" if avg_faithfulness >= 0.90 and all_abstentions_passed else "FAILED",
            "average_faithfulness": avg_faithfulness,
            "hallucination_rate": hallucination_rate,
            "all_abstentions_passed": all_abstentions_passed,
            "cataloged_evaluations": results,
            "abstention_evaluations": abstention_results
        }


rag_evaluator = RAGEvaluator()
